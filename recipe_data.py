"""Starter North Indian recipe set.

Quantities are in each ingredient's catalogue unit (g, ml or pc; see ingredient_catalog.py)
for the whole dish, not per serving. Prices and calories come from the catalogue, so
cost/nutrition stay consistent across recipes. All figures are illustrative estimates.
"""
from dataclasses import dataclass

from ingredient_catalog import CATALOG

MEALS = ("Breakfast", "Lunch", "Dinner", "Snacks")


@dataclass(frozen=True)
class Recipe:
    id: int
    name: str
    meals: tuple            # first entry is the recipe's best-fit meal
    time_min: int
    difficulty: str
    servings: int
    emoji: str
    ingredients: tuple      # ((ingredient_id, quantity), ...) - ids unique per recipe
    steps: tuple
    image: str = ""         # optional photo URL; a themed illustration is used otherwise

    @property
    def vegetarian(self) -> bool:
        return all(CATALOG[i].veg for i, _ in self.ingredients)


def _img(photo_id: str) -> str:
    return f"https://images.unsplash.com/{photo_id}?auto=format&fit=crop&w=600&q=70"


def _r(id, name, meals, time_min, difficulty, servings, emoji, ingredients, steps, image=""):
    return Recipe(id, name, tuple(meals), time_min, difficulty, servings, emoji,
                  tuple(ingredients), tuple(steps), _img(image) if image else "")


